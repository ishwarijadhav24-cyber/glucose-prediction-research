"""Write backend/requirements-lock.txt and backend/requirements-dev.txt from the VALIDATED environment.

The dependency closure is computed from the installed packages' declared requirements, with
environment markers evaluated for Linux x86_64 / CPython 3.13 (the container target), so only
packages that the runtime really needs are pinned, at exactly the versions the tests ran with.
Run from the repository root: python backend/scripts/lock_requirements.py
"""

import importlib.metadata as md
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[2]
RUNTIME_ROOTS = ["lightgbm", "scikit-learn", "numpy", "pandas", "joblib", "lxml", "fastapi", "starlette",
                 "pydantic", "pydantic-settings", "python-multipart", "uvicorn", "matplotlib", "seaborn"]
DEV_ROOTS = ["pytest", "httpx"]
LINUX = {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix", "platform_machine": "x86_64",
         "implementation_name": "cpython", "python_version": "3.13", "python_full_version": "3.13.9", "extra": ""}


def closure(roots):
    env = dict(default_environment(), **LINUX)
    seen, stack = {}, list(roots)
    while stack:
        name = stack.pop()
        key = name.lower().replace("_", "-")
        if key in seen:
            continue
        dist = md.distribution(name)            # raises if a Linux dependency is not installed here
        seen[key] = dist.version
        for req in dist.requires or []:
            r = Requirement(req)
            if r.marker is None or r.marker.evaluate(env):
                stack.append(r.name)
    return seen


def write(path, header, pins):
    lines = [f"# {h}" for h in header] + [f"{k}=={v}" for k, v in sorted(pins.items())]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    runtime = closure(RUNTIME_ROOTS)
    dev = {k: v for k, v in closure(DEV_ROOTS).items() if k not in runtime}
    write(ROOT / "backend" / "requirements-lock.txt",
          ["Runtime lock: complete closure of backend/requirements.txt (Linux x86_64, CPython 3.13).",
           "Generated by backend/scripts/lock_requirements.py from the validated environment. Do not edit.",
           "Install with: pip install --no-deps -r backend/requirements-lock.txt"], runtime)
    write(ROOT / "backend" / "requirements-dev.txt",
          ["Test/development only (not installed in the production image).",
           "Generated by backend/scripts/lock_requirements.py. Use together with requirements-lock.txt:",
           "pip install --no-deps -r backend/requirements-lock.txt -r backend/requirements-dev.txt"], dev)
    print(f"runtime: {len(runtime)} packages, dev-only: {len(dev)} packages")
