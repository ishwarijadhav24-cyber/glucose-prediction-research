"""Structured backend errors. HTTP mapping is added with the API (Phase 3).

Messages never contain uploaded values (privacy).
"""

from enum import Enum


class ErrorCode(str, Enum):
    INVALID_FILE = "INVALID_FILE"
    INVALID_FORMAT = "INVALID_FORMAT"
    MISSING_COLUMNS = "MISSING_COLUMNS"
    INVALID_TIMESTAMP = "INVALID_TIMESTAMP"
    DUPLICATE_TIMESTAMP = "DUPLICATE_TIMESTAMP"
    INSUFFICIENT_HISTORY = "INSUFFICIENT_HISTORY"
    MISSING_CURRENT_GLUCOSE = "MISSING_CURRENT_GLUCOSE"
    INVALID_NUMERIC_VALUE = "INVALID_NUMERIC_VALUE"
    NAN_AFTER_PREPROCESSING = "NAN_AFTER_PREPROCESSING"
    INFINITE_FEATURE = "INFINITE_FEATURE"
    FEATURE_SCHEMA_MISMATCH = "FEATURE_SCHEMA_MISMATCH"
    MODEL_NOT_AVAILABLE = "MODEL_NOT_AVAILABLE"
    PREDICTION_FAILED = "PREDICTION_FAILED"
    NOT_FOUND = "NOT_FOUND"
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    RATE_LIMITED = "RATE_LIMITED"
    PREDICTION_TIMEOUT = "PREDICTION_TIMEOUT"
    SERVER_BUSY = "SERVER_BUSY"
    UNSUPPORTED_ENCODING = "UNSUPPORTED_ENCODING"
    UNSUPPORTED_FORMAT = "UNSUPPORTED_FORMAT"
    UNSUPPORTED_SAMPLING = "UNSUPPORTED_SAMPLING"


HTTP_STATUS = {
    ErrorCode.INVALID_FILE: 400, ErrorCode.FILE_TOO_LARGE: 413, ErrorCode.NOT_FOUND: 404,
    ErrorCode.INVALID_FORMAT: 422, ErrorCode.MISSING_COLUMNS: 422, ErrorCode.INVALID_TIMESTAMP: 422,
    ErrorCode.DUPLICATE_TIMESTAMP: 422, ErrorCode.INVALID_NUMERIC_VALUE: 422,
    ErrorCode.INSUFFICIENT_HISTORY: 422, ErrorCode.MISSING_CURRENT_GLUCOSE: 422,
    ErrorCode.NAN_AFTER_PREPROCESSING: 500, ErrorCode.INFINITE_FEATURE: 422,
    ErrorCode.FEATURE_SCHEMA_MISMATCH: 500, ErrorCode.PREDICTION_FAILED: 500,
    ErrorCode.MODEL_NOT_AVAILABLE: 503, ErrorCode.INTERNAL_ERROR: 500,
    ErrorCode.RATE_LIMITED: 429, ErrorCode.PREDICTION_TIMEOUT: 504, ErrorCode.SERVER_BUSY: 503,
    ErrorCode.UNSUPPORTED_ENCODING: 415, ErrorCode.UNSUPPORTED_FORMAT: 422, ErrorCode.UNSUPPORTED_SAMPLING: 422,
}


class BackendError(Exception):
    def __init__(self, code: ErrorCode, message: str):
        super().__init__(message)
        self.code = code
        self.message = message

    @property
    def http_status(self) -> int:
        return HTTP_STATUS[self.code]

    def __repr__(self):
        return f"BackendError({self.code.value}: {self.message})"
