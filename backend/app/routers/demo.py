import pandas as pd
from fastapi import APIRouter, Body, Depends, Request

from backend.app.errors import BackendError, ErrorCode
from backend.app.routers.common import service, to_response
from backend.app.security import rate_limit, run_bounded
from backend.app.schemas import (DemoPatientData, DemoPatientList, DemoPatientSummary, DemoPrediction,
                                 DemoPredictRequest, EventPoint, GlucosePoint)

router = APIRouter(prefix="/api/v1", tags=["demo"])
FIVE = pd.Timedelta("5min")
NOTE = ("Synthetic demonstration data (generated by backend/scripts/make_synthetic_demo.py; not from any real person). "
        "Uploaded data is never added here. Predictions use only data at or before the prediction time.")


def _patient(request: Request, patient_id: str) -> pd.DataFrame:
    ev = request.app.state.demo.get(patient_id)
    if ev is None:
        raise BackendError(ErrorCode.NOT_FOUND, "Unknown demo patient.")
    return ev


def _summary(pid: str, ev: pd.DataFrame) -> DemoPatientSummary:
    g = ev.loc[ev["glucose_mg_dl"].notna(), "timestamp"]
    return DemoPatientSummary(patient_id=pid, n_glucose_readings=len(g),
                              start=g.min().to_pydatetime(), end=g.max().to_pydatetime())


@router.get("/demo/patients", response_model=DemoPatientList, summary="List demo patients")
def list_patients(request: Request):
    store = request.app.state.demo
    return DemoPatientList(patients=[_summary(p, store.get(p)) for p in store.ids()], note=NOTE)


@router.get("/demo/patients/{patient_id}", response_model=DemoPatientData, summary="Historical demo data")
def get_patient(patient_id: str, request: Request):
    ev = _patient(request, patient_id)

    def points(col, cls, key):
        sel = ev[ev[col].notna()]
        return [cls(timestamp=t.to_pydatetime(), **{key: float(v)}) for t, v in zip(sel["timestamp"], sel[col])]

    s = _summary(patient_id, ev)
    return DemoPatientData(**s.model_dump(), glucose=points("glucose_mg_dl", GlucosePoint, "glucose_mg_dl"),
                           bolus_units=points("bolus_units", EventPoint, "value"),
                           carbs_g=points("carbs_g", EventPoint, "value"))


@router.post("/predict/demo/{patient_id}", response_model=DemoPrediction, dependencies=[Depends(rate_limit)],
             summary="30-minute forecast for a demo patient at a chosen (past) time")
async def predict_demo(patient_id: str, request: Request, body: DemoPredictRequest | None = Body(default=None)):
    ev = _patient(request, patient_id)
    t = pd.Timestamp(body.prediction_time) if body and body.prediction_time else None
    if t is not None and t.tzinfo is not None:
        raise BackendError(ErrorCode.INVALID_TIMESTAMP, "prediction_time must be local time without a time zone.")
    result = await run_bounded(request, service(request).predict, ev, t)   # service drops every event after t
    # Display only, computed AFTER the prediction from the recorded data: reading in (forecast - 5 min, forecast]
    g = ev[ev["glucose_mg_dl"].notna()]
    win = g[(g["timestamp"] > result.forecast_time - FIVE) & (g["timestamp"] <= result.forecast_time)]
    actual = float(win["glucose_mg_dl"].iloc[-1]) if len(win) else None
    return to_response(request, result, cls=DemoPrediction, actual_glucose_mg_dl_at_forecast_time=actual)
